const add = async ({ title, date, amount, income = false, transfer = false }) => {
  await page.getByRole('button', { name: 'Tambah transaksi', exact: true }).last().click()
  const dialog = page.getByRole('dialog')
  if (income) await dialog.getByRole('button', { name: 'Pemasukan', exact: true }).click()
  if (transfer) await dialog.getByRole('button', { name: 'Transfer', exact: true }).click()
  else await dialog.getByPlaceholder(income ? 'Contoh: Gaji bulanan' : 'Contoh: Makan siang').fill(title)
  await dialog.getByLabel('Nominal (Rp)').fill(String(amount))
  await dialog.getByLabel('Tanggal', { exact: true }).fill(date)
  if (transfer) {
    await dialog.getByLabel('Akun tujuan').selectOption({ label: 'GoPay' })
    await dialog.getByLabel('Biaya admin').fill('2500')
  }
  await dialog.getByRole('button', { name: 'Simpan transaksi', exact: true }).click()
  await dialog.waitFor({ state: 'hidden' })
}
const range = async (start = '2026-02-20', end = '2026-03-05') => {
  await page.getByRole('button', { name: 'Rentang tanggal', exact: true }).click()
  await page.getByLabel('Dari tanggal', { exact: true }).fill(start)
  await page.getByLabel('Sampai tanggal', { exact: true }).fill(end)
  const caption = displayRange(start, end)
  await page.locator('.history-results-head p, .report-period-context').filter({ hasText: caption }).waitFor()
}
const waitCount = async (selector, count) => page.waitForFunction(({ selector, count }) => document.querySelectorAll(selector).length === count, { selector, count })
const amount = async (locator) => Number((await locator.textContent()).replace(/[^\d-]/g, ''))
const noOverflow = async () => {
  // Responsive charts finish resizing in ResizeObserver after viewport changes.
  await page.waitForFunction(() => document.documentElement.scrollWidth <= window.innerWidth, null, { timeout: 5000 })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `horizontal overflow at ${page.url()}`)
}
const downloadText = async (button) => {
  const pending = page.waitForEvent('download')
  await button.click()
  const download = await pending
  const path = await download.path()
  return readFile(path, 'utf8')
}

